#!/usr/bin/env node
/*
 * Generates docs/INPUT_OUTPUT_MAP.md from the application's model layer, so the
 * documented mapping of inputs, outputs, formulas and dependencies is always
 * the one the application actually uses.
 * Usage: node tools/generate_docs.js
 */
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "..");
globalThis.window = globalThis;
require(path.join(ROOT, "app/data/model_data.js"));
require(path.join(ROOT, "app/assets/js/formula.js"));
require(path.join(ROOT, "app/assets/js/engine.js"));
const M = require(path.join(ROOT, "app/assets/js/model.js"));
const model = new M.Model(globalThis.PV_WORKBOOK), eng = model.engine;
const st = model.workbookState();
// Upstream inputs, stopping at the Inputs sheet's final values (Inputs!F = country default or user override)
function upstream(key) {
  const seen = {}, out = [];
  (function walk(k) {
    if (seen[k]) return; seen[k] = 1;
    if (/^Inputs!F\d+$/.test(k) || !eng.formulaOf(k)) { if (eng.cells[k]) out.push(k); return; }
    eng.precedents(k).forEach(walk);
  })(key);
  return out.filter(k => !/!B\d+$/.test(k));
}
const esc = s => String(s).replace(/\|/g, "\\|").replace(/\n\s*/g, " ");
const fmt = v => typeof v === "number" ? (Math.abs(v) >= 1e6 || (Math.abs(v) < 1e-3 && v !== 0) ? v.toExponential(3) : Number(v.toPrecision(6)).toString()) : String(v);
const L = [];
L.push("# Input / Output / Formula Map", "", "_Generated by `node tools/generate_docs.js` from the application's model layer (app/assets/js/model.js) and the extracted workbook. Values: China, 2025, workbook defaults._", "");
L.push("Sheet abbreviation: **CMC** = `Cost Model_Calculations`. Year columns D…N = 2020…2030 (2025 = column I). Import tables: Country_Index columns D…I = 2025…2030.", "");

L.push("## 1. Outputs", "", "| Output | Unit | TOPCon cell | Mono PERC cell | Formula (2025, TOPCon) | Value China 2025 TOPCon / Mono |", "|---|---|---|---|---|---|");
const outs = [["Total module cost with ESG (headline)", "USD/Wp", 96, 192], ["Total module cost without ESG", "USD/Wp", 95, 191], ["Module power rating", "W/module", 77, 173], ["Watt-peak per wafer", "Wp", 35, 131]];
for (const [lab, u, t, m] of outs) L.push(`| ${lab} | ${u} | CMC!I${t} | CMC!I${m} | \`${esc(eng.formulaOf("Cost Model_Calculations!I" + t))}\` | ${fmt(eng.cachedValue("Cost Model_Calculations!I" + t))} / ${fmt(eng.cachedValue("Cost Model_Calculations!I" + m))} |`);
L.push(`| Output_Visualization waterfall totals | USD/Wp | Output_Visualization!C203 (2025), C219 (2030) | C211, C227 | \`${esc(eng.formulaOf("Output_Visualization!C199"))}\` … | ${fmt(eng.cachedValue("Output_Visualization!C203"))} / ${fmt(eng.cachedValue("Output_Visualization!C211"))} |`);
L.push("", "USD per module (derived in the app) = total USD/Wp × module power rating.", "");

L.push("## 2. Stage totals and cost components", "");
for (const t of ["topcon", "mono"]) {
  const T = M.TECH[t];
  L.push(`### ${T.longLabel}`, "", "| Stage | Component | Cost type | Row | Formula (2025) | Value 2025 (China) | Upstream inputs (transitive, non-formula cells) |", "|---|---|---|---|---|---|---|");
  for (const s of M.STAGES) {
    const spec = T.stages[s.id];
    for (const [row, type] of spec.comps) {
      const key = "Cost Model_Calculations!I" + row, ups = upstream(key);
      L.push(`| ${s.label} | ${M.COMP[type].label} | ${M.CATEGORIES[M.COMP[type].cat].label} | ${row} | \`${esc(eng.formulaOf(key) || "(constant)")}\` | ${fmt(eng.cachedValue(key))} ${s.id === "poly" ? "USD/kg" : "USD/Wp"} | ${ups.slice(0, 14).map(k => "`" + k.replace("Cost Model_Calculations", "CMC") + "`").join(", ")}${ups.length > 14 ? " …(+" + (ups.length - 14) + ")" : ""} |`);
    }
    const tk = "Cost Model_Calculations!I" + spec.total;
    L.push(`| **${s.label}** | **Stage total (with sourcing switch)** | | ${spec.total} | \`${esc(eng.formulaOf(tk))}\` | **${fmt(eng.cachedValue(tk))} USD/Wp** | |`);
  }
  L.push("");
}

L.push("## 3. Editable inputs (application parameters)", "", "Kinds: **input** = country-specific value on the Inputs sheet (the app writes the `User Input` column E, exactly like a workbook user); **scalar** = single Assumptions cell; **series** = yearly row scaled by a multiplier (trajectory preserved); **import** = import-price table scaled; **global** = hardcoded formula constant exposed as a parameter.", "");
L.push("| Parameter id | Input | Kind | Stage | Classification | Unit | Value (China 2025) | Editable | Workbook source |", "|---|---|---|---|---|---|---|---|---|");
for (const p of M.PARAMS) {
  const s2 = JSON.parse(JSON.stringify(st)); s2.tech = p.tech === "both" ? "topcon" : p.tech;
  if (p.kind === "import") { s2.country = "Vietnam"; }
  const v = model.baselineValue(p, s2);
  L.push(`| \`${p.id}\` | ${esc(p.label)} | ${p.kind} | ${p.stage} | ${p.cls}${p.countrySpecific ? " · country-specific" : ""} | ${esc(p.unit)} | ${fmt(v)}${p.kind === "import" ? " (China→Vietnam)" : ""} | ${p.editable ? "yes" : p.noEffect ? "no (no effect)" : "no (fixed)"} | \`${esc(p.source)}\` |`);
}
L.push("", "## 4. Workbook cells not used by any cost formula", "", "| Cell | Label | Value |", "|---|---|---|");
const reach = {}, stack = [];
M.YEAR_COLS.forEach(c => [96, 192, 77, 173].forEach(r => stack.push("Cost Model_Calculations!" + c + r)));
while (stack.length) { const k = stack.pop(); if (reach[k]) continue; reach[k] = 1; eng.precedents(k).forEach(x => stack.push(x)); }
for (const k of Object.keys(eng.cells)) {
  const m = /^(Assumptions)!([DE])(\d+)$/.exec(k) || /^(Inputs)!(F)(\d+)$/.exec(k);
  if (!m || typeof eng.cells[k].v !== "number" && !eng.cells[k].f || reach[k]) continue;
  const lab = eng.cells[m[1] + "!B" + m[3]];
  L.push(`| \`${k}\` | ${lab ? esc(lab.v) : ""} | ${fmt(eng.cachedValue(k))} |`);
}
L.push("", "## 5. Dependency structure", "", "```",
  "Country_Index (country defaults) ──INDEX/MATCH──► Inputs!D ─┐",
  "User override (Inputs!E) ────────────────────────────────────┴─► Inputs!F (final value)",
  "Assumptions (lifetimes, maintenance, labour intensity, overheads, …) ─┐",
  "Hardcoded yearly series in CMC (electricity use, prices, efficiencies) ┼─► stage component rows",
  "Inputs!F (electricity price, salary, CAPEX, capacity) ────────────────┘",
  "stage components ─► Final costs (SUM) ─► +15% operating profit ─► + overheads (rate × 0.9 × price)",
  "   ─► stage price; for 2025–2030: IF(source = Domestic, own price, Country_Index import price)",
  "four stage prices ─► Total module cost (CMC rows 95/96, 191/192) ─► Output_Visualization waterfalls",
  "```", "", "No circular references exist (verified by the engine's cycle detection while evaluating all 1,506 formulas).", "");
fs.writeFileSync(path.join(ROOT, "docs/INPUT_OUTPUT_MAP.md"), L.join("\n"));
console.log("Wrote docs/INPUT_OUTPUT_MAP.md");
